//! 设置页三页 · `character` 子面的 **wasm 宿主挂载**模块（**预置空桩**）。
//!
//! ⚠️ 预置空桩 ⇒ 由**该子面的施工线独占写入**。
//!
//! 职责：把 `ui_kit::settings_character` 的组件挂到页面的 `#app` 容器里
//! （照批一/批二的 app mode 形态：宿主注入数据 → 组件渲染 → 不碰数据面）。

/// wasm 宿主挂载（**预置空桩**：该面**尚未迁移** ⇒ 显式报「未接线」）。
///
/// ## 为什么要留一个「显式报错」的桩
///
/// 共享的 `settings_dispatch.rs` 会**分发**到本函数 ⇒ 若本模块**不存在**，
/// 则**整个 wasm 构建失败** ⇒ 一个面没迁移会**连累所有面**。
/// ⇒ 留一个**显式报错**的桩 ⇒ 构建保持绿，**运行到这一面时显式说「未接线」**
/// ⇒ **不假装已接线**（0 装）。
#[cfg(target_arch = "wasm32")]
pub mod wasm {
    /// 挂载该面。**未迁移** ⇒ 显式报错。
    pub fn mount(container: &web_sys::Element) -> Result<(), String> {
        let _ = container;
        Err("该面尚未迁移 ⇒ 挂载未接线（预置空桩）".into())
    }
}
