#   NOT IMPLEMENTED < IMPLEMENTED < PRODUCTION WIRED < HARDWARE VALIDATED
# `DEFAULT ENABLED` **不是一级**，而是横切属性 —— 由 `default: "ON" | "OFF" | null`
# 字段表达（"接线了" 与 "默认开" 是两件事：可以 PRODUCTION WIRED 且默认关）。
# 历史文档把两者并列成"四级"，导致同一能力出现两种说法；此处以 schema 为准。
LEVELS = (
    "NOT IMPLEMENTED",
    "IMPLEMENTED",
    "PRODUCTION WIRED",
    "HARDWARE VALIDATED",
)
DEFAULT_VALUES = ("ON", "OFF")
REQUIRED = ("id", "title", "level", "sources", "verified_at", "owner", "next_review")
LIST_KEYS = ("sources", "tests")


# ---------------------------------------------------------------- loading

def _scalar(text: str):
    text = text.strip()
    if not text:
        return None
    if len(text) >= 2 and text[0] == text[-1] and text[0] in ("'", '"'):
        return text[1:-1]
    low = text.lower()
    if low in ("null", "~"):
        return None
    if low == "true":
        return True
    if low == "false":
        return False
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    return text


def _load_minimal_yaml(text: str) -> dict:
    """解析本仓库 claims.yaml 用到的 YAML 子集（顶层标量 + claims 列表）。"""
    lines = []
    for raw in text.splitlines():
        stripped = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if stripped.strip():
            lines.append(stripped)

    data: dict = {}
    claims: list = []
    current: dict | None = None
    list_key: str | None = None
    in_claims = False
    for line in lines:
        indent = len(line) - len(line.lstrip(" "))
        body = line.strip()
        if body.startswith("#"):
            continue
        if not in_claims:
            if body == "claims:":
                in_claims = True
                data["claims"] = claims
                continue
            key, _, value = body.partition(":")
            data[key.strip()] = _scalar(value)
            continue
        if indent >= 4 and body.startswith("- ") and list_key:
            current.setdefault(list_key, []).append(_scalar(body[2:]))
            continue
        if indent <= 2 and body.startswith("- "):
            if current is not None:
                claims.append(current)
            current = {}
            list_key = None
            key, _, value = body[2:].partition(":")
            current[key.strip()] = _scalar(value)
            continue
        if current is None:
            continue
        key, _, value = body.partition(":")
        key = key.strip()
        if value.strip() == "":
            current[key] = []
            list_key = key
        else:
            current[key] = _scalar(value)
            list_key = None
    if current is not None:
        claims.append(current)
    return data


def load_claims(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    try:
        import yaml  # type: ignore
    except ImportError:
        return _load_minimal_yaml(text)
    data = yaml.safe_load(text) or {}
    data.setdefault("claims", [])
    return data


# ---------------------------------------------------------------- helpers

def _run(args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(args, cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace")


def grep_in_crates(needle: str) -> bool:
    proc = _run(["git", "grep", "-q", "--fixed-strings", needle, "--", "crates"])
    if proc.returncode in (0, 1):
        return proc.returncode == 0
    # fallback: 逐文件扫描（git 不可用时）
    for path in (ROOT / "crates").rglob("*"):
        if path.is_file() and path.suffix in (".rs", ".toml"):
            try:
                if needle in path.read_text(encoding="utf-8", errors="ignore"):
                    return True
            except OSError:
                continue
    return False


def changed_since(commit: str, sources: list[str]) -> list[str]:
    """返回 working tree（相对 commit）被改过的 sources。"""
    proc = _run(["git", "diff", "--name-only", commit, "--", *sources])
    if proc.returncode != 0:
        return [f"<git diff failed: {proc.stderr.strip()}>"]
    return [line.strip() for line in proc.stdout.splitlines() if line.strip()]


def changed_in_scope_dirs(commit: str, sources: list[str]) -> list[str]:
    """**目录级兜底**：返回 `sources` 所在目录里、相对 commit 被改过的**其他**文件。

    # 为什么需要它（2026-10-28 审计认定 H3：**漏列 source 即静默漂**）

    原 STALE 判据只比对**声明里列出的 sources**
    ⇒ ⇒ 若某条 claim 的真实依据文件**没被列进去** ⇒ ⇒ **永远不会 STALE**
    ⇒ ⇒ 声明与代码可以无限脱节，而**没有任何守卫会发现**。

    ⇒ 兜底做法：取每条 source 的**所在目录**，看该目录下有没有**未被列出**的文件变过
    ⇒ ⇒ 命中就报「**可疑漏列**」（不是直接判 STALE，因为同目录变更未必影响该声明）
    ⇒ ⇒ 让**沉默的漏列变成可见的提示**。

    ⚠️ 口径：只下探一层目录（`main.rs` → `src/`），不递归整个 crate ⇒ 避免噪声爆炸；
    且**排除**已列出的 source 自身（那些由 [`changed_since`] 负责）。
    """
    listed = {path.strip() for path in sources}
    # ⚠️ **只对窄目录兜底**：宽目录（如 `crates/adapters/cli/src/`，几十个文件）
    #   天天有变动 ⇒ 兜底会变成噪声（实测 29 条里 17 条命中）⇒ ⇒ 噪声 = 训练人忽略告警。
    #   口径：该目录下**被 git 跟踪**的文件数 ≤ `NARROW_DIR_MAX_FILES` 才算窄目录。
    NARROW_DIR_MAX_FILES = 8
    dirs: set[str] = set()
    for path in listed:
        parent = str(Path(path).parent)
        if not parent or parent == ".":
            continue
        proc = _run(["git", "ls-files", parent])
        tracked = [line for line in proc.stdout.splitlines() if line.strip()]
        if 0 < len(tracked) <= NARROW_DIR_MAX_FILES:
            dirs.add(parent)
    if not dirs:
        return []
    proc = _run(["git", "diff", "--name-only", commit, "--", *sorted(dirs)])
    if proc.returncode != 0:
        return []
    return [
        line.strip()
        for line in proc.stdout.splitlines()
        if line.strip() and line.strip() not in listed
    ]


def _today() -> _dt.date:
    return _dt.date.today()


# ---------------------------------------------------------------- test baseline / README badge

BASELINE = ROOT / "docs" / "03-reference" / "test-baseline.md"
MATRIX = ROOT / "docs" / "03-reference" / "capabilities-matrix.md"
READMES = (ROOT / "README.md", ROOT / "README.zh-CN.md")
BADGE_RE = re.compile(r"tests-\d+%20passed%20%7C%20\d+%20failed%20\([0-9-]+\)-(?:success|critical)\.svg")


def baseline_numbers() -> dict:
    """从单一真源 test-baseline.md 读测试数字（不手抄）。"""
    text = BASELINE.read_text(encoding="utf-8")
    m = re.search(r"(\d+)\s*套件\s*/\s*(\d+)\s+passed\s*/\s*(\d+)\s+failed", text)
    if not m:
        raise SystemExit(f"cannot parse baseline numbers from {BASELINE}")
    d = re.search(r"\|\s*\*\*日期\*\*\s*\|\s*(\d{4}-\d{2}-\d{2})", text)
    if not d:
        raise SystemExit(f"cannot parse baseline date from {BASELINE}")
    tail = text[m.start(): text.find("\n", m.end()) if text.find("\n", m.end()) != -1 else len(text)]
    ignored = re.search(r"(\d+)\s+ignored", tail)
    return {
        "suites": int(m.group(1)),
        "passed": int(m.group(2)),
        "failed": int(m.group(3)),
        "ignored": int(ignored.group(1)) if ignored else 0,
        "date": d.group(1),
    }


def badge_url() -> str:
    n = baseline_numbers()
    dash_date = n["date"].replace("-", "--")
    status = "success" if n["failed"] == 0 else "critical"
    return f"tests-{n['passed']}%20passed%20%7C%20{n['failed']}%20failed%20({dash_date})-{status}.svg"


def sync_badges(write: bool) -> int:
    """把两份 README 的 tests 徽章同步为单一真源数字。"""
    want = badge_url()
    changed = 0
    for path in READMES:
        text = path.read_text(encoding="utf-8")
        new_text, count = BADGE_RE.subn(want, text)
        if count != 1:
            print(f"FAIL: expected exactly 1 tests badge in {path.relative_to(ROOT)}, found {count}", file=sys.stderr)
            return 1
        if new_text != text:
            changed += 1
            if write:
                path.write_text(new_text, encoding="utf-8")
            print(f"{'updated' if write else 'would update'}: {path.relative_to(ROOT)}")
    print(f"badge target: {want}  (baseline {baseline_numbers()})")
    if not changed:
        print("OK: badges already match baseline")
    return 0


def matrix_env_tokens() -> list[str]:
    text = MATRIX.read_text(encoding="utf-8")
    tokens: list[str] = []
    for m in re.finditer(r"APEIRETH_[A-Z0-9_]+", text):
        token = m.group(0)
        # 通配写法（APEIRETH_ENABLE_* / APEIRETH_DISABLE_*）跳过
        if text[m.end():m.end() + 1] == "*":
            continue
        if token.endswith("_"):
            continue
        tokens.append(token)
    return sorted(set(tokens))


def cmd_matrix_check(strict: bool) -> int:
    tokens = matrix_env_tokens()
    missing = [t for t in tokens if not grep_in_crates(t)]
    print(f"matrix env tokens: {len(tokens)}; missing in crates/: {len(missing)}")
    for token in missing:
        print(f"  MISSING: {token}")
    # claims 的 switch_env 应出现在 matrix（状态表与开关表互钉）
    data = load_claims(DEFAULT_CLAIMS)
    matrix_text = MATRIX.read_text(encoding="utf-8")
    claim_missing = [
        str(claim.get("switch_env"))
        for claim in data.get("claims") or []
        if claim.get("switch_env") and str(claim["switch_env"]) not in matrix_text
    ]
    if claim_missing:
        print(f"claims switch_env not present in matrix: {', '.join(claim_missing)}")
    if missing or claim_missing:
        return 1 if strict else 0
    print("OK: matrix env tokens all found in crates/; claims switches all present in matrix")
    return 0


