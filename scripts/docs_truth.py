def cmd_verify(claims_path: Path, strict: bool, block_stale: bool = False) -> int:
    data = load_claims(claims_path)
    claims = data.get("claims") or []
    if not claims:
        print(f"FAIL: no claims in {claims_path}", file=sys.stderr)
        return 1

    seen: set[str] = set()
    rows: list[dict] = []
    errors = 0
    stale_count = 0
    suspected_count = 0
    review_count = 0
    for i, claim in enumerate(claims, 1):
        cid = str(claim.get("id") or f"<claim-{i}>")
        problems: list[str] = []
        stale: list[str] = []

        if cid in seen:
            problems.append("duplicate id")
        seen.add(cid)
        for field in REQUIRED:
            if not claim.get(field):
                problems.append(f"missing field: {field}")
        level = claim.get("level")
        if level and level not in LEVELS:
            if level == "DEFAULT ENABLED":
                problems.append(
                    "level 不能写 DEFAULT ENABLED: 它不是一级, 是横切属性; "
                    '改用 level: PRODUCTION WIRED + default: "ON"'
                )
            else:
                problems.append(f"unknown level: {level}")
        default_value = claim.get("default")
        if default_value not in (None, *DEFAULT_VALUES):
            problems.append(f'default 只认 "ON" / "OFF" / null, 实为: {default_value!r}')
        sources = claim.get("sources") or []
        if not isinstance(sources, list) or not sources:
            problems.append("sources must be a non-empty list")
            sources = []
        for src in sources:
            if not (ROOT / src).exists():
                problems.append(f"source missing: {src}")
        for test in claim.get("tests") or []:
            if not (ROOT / test).exists():
                problems.append(f"test path missing: {test}")
        switch = claim.get("switch_env")
        if switch and not grep_in_crates(str(switch)):
            problems.append(f"switch_env not found in crates/: {switch}")
        verified_at = claim.get("verified_at")
        if sources and verified_at:
            stale = changed_since(str(verified_at), sources)
            # ⚠️ **目录级兜底**（H3）：同目录下**未列出**的文件变过 ⇒ 提示「疑似漏列」
            # ⇒ ⇒ 把「沉默的漏列」变成可见提示（不影响 stale 判定本身）。
            suspected_missing = changed_in_scope_dirs(str(verified_at), sources)
        review_due = False
        next_review = claim.get("next_review")
        if next_review:
            try:
                review_due = _dt.date.fromisoformat(str(next_review)) < _today()
            except ValueError:
                problems.append(f"bad next_review date: {next_review}")

        if problems:
            status = "FAIL"
            errors += 1
        elif stale:
            status = "STALE"
            stale_count += 1
        elif review_due:
            status = "REVIEW_DUE"
            review_count += 1
        else:
            status = "OK"
        rows.append(
            {
                "id": cid,
                "level": level,
                "default": claim.get("default"),
                "switch": switch,
                "status": status,
                "detail": "; ".join(
                    problems
                    + [f"changed: {s}" for s in stale[:3]]
                    # ⚠️ 疑似漏列（H3）：同目录下未列出的文件变过
                    + [
                        f"**疑似漏列 source**: {s}"
                        for s in suspected_missing[:3]
                    ]
                ),
                "suspected": len(suspected_missing),
            }
        )

    width = max(len(r["id"]) for r in rows)
    print(f"{'id'.ljust(width)}  {'status':<10}  {'level':<18}  {'default':<7}  switch")
    print("-" * (width + 55))
    for r in rows:
        print(
            f"{r['id'].ljust(width)}  {r['status']:<10}  {str(r['level'] or '-'):<18}  "
            f"{str(r['default'] if r['default'] is not None else '-'):<7}  {r['switch'] or '-'}"
        )
        if r["detail"]:
            print(f"{''.ljust(width)}  -> {r['detail']}")
    print()
    suspected_count = sum(1 for r in rows if r.get("suspected"))
    print(
        f"claims={len(rows)} fail={errors} stale={stale_count} review_due={review_count}"
        f" suspected_missing={suspected_count}"
    )
    if suspected_count:
        print(
            "  ⚠️ suspected_missing = 「同目录下有**未列出**的文件变过」的声明数"
            " ⇒ 提示**可能漏列 source**（不会判失败，但应当复核）"
        )
    if errors:
        return 1
    if block_stale and stale_count:
        return 1
    if strict and (stale_count or review_count):
        return 1
    return 0


def render_status() -> str:
    data = load_claims(DEFAULT_CLAIMS)
    claims = data.get("claims") or []
    lines = [
        "# 文档状态仪表盘（STATUS）",
        "",
        GENERATED_MARK,
        f"> 真源：[claims.yaml](claims.yaml) · 生成器：`scripts/docs_truth.py --gen` · 更新：{data.get('updated_at', '-')}",
        "",
        "| id | level | default | switch_env | verified_at | next_review |",
        "|---|---|---|---|---|---|",
    ]
    for claim in claims:
        lines.append(
            "| `{id}` | {level} | {default} | {switch} | `{verified_at}` | {next_review} |".format(
                id=claim.get("id", "-"),
                level=claim.get("level", "-"),
                default=claim.get("default") if claim.get("default") is not None else "-",
                switch=f"`{claim['switch_env']}`" if claim.get("switch_env") else "-",
                verified_at=str(claim.get("verified_at", "-"))[:12],
                next_review=claim.get("next_review") or "-",
            )
        )
    lines += [
        "",
        "## 使用",
        "",
        "- 改状态：先改源码/测试 → 更新 `claims.yaml` 对应条的 `verified_at` → 跑 `python scripts/docs_truth.py --verify` → `--gen`。",
        "- `--verify` 的 STALE = 源码在 `verified_at` 之后被改过（该条声明需要复核）；FAIL = 证据缺失/开关不存在/字段不全。",
        "- P0 为 report-only（STALE 不阻塞 CI）；P1 起对 changed-claim 阻塞。",
        "",
    ]
    return "\n".join(lines)


def cmd_gen() -> int:
    STATUS_DOC.parent.mkdir(parents=True, exist_ok=True)
    STATUS_DOC.write_text(render_status(), encoding="utf-8")
    print(f"generated: {STATUS_DOC.relative_to(ROOT)}")
    return 0


def parse_test_log(path: Path) -> dict:
    """从一次全量 `cargo test` 日志汇总 套件/passed/failed/ignored。"""
    text = path.read_text(encoding="utf-8", errors="replace")
    pattern = re.compile(r"test result: (?:ok|FAILED)\. (\d+) passed; (\d+) failed; (\d+) ignored")
    suites = passed = failed = ignored = 0
    for match in pattern.finditer(text):
        suites += 1
        passed += int(match.group(1))
        failed += int(match.group(2))
        ignored += int(match.group(3))
    if suites == 0:
        raise SystemExit(f"no 'test result' lines found in {path}")
    return {"suites": suites, "passed": passed, "failed": failed, "ignored": ignored}


def cmd_baseline_check(log: str) -> int:
    lp = Path(log)
    if not lp.is_absolute():
        lp = ROOT / lp
    got = parse_test_log(lp)
    base = baseline_numbers()
    print(f"log : {got}")
    print(f"SSoT: {base}")
    diff = {k: (base.get(k), got[k]) for k in ("suites", "passed", "failed", "ignored") if base.get(k) != got[k]}
    if diff:
        print(f"FAIL: log totals != test-baseline §1: {diff}", file=sys.stderr)
        return 1
    print("OK: log totals match test-baseline §1")
    return 0


def cmd_gen_matrix_01(write: bool, force: bool) -> int:
    """把 matrix §0.1 的 结果/日期 两行同步为单一真源（默认 dry-run；文件有在途改动时拒绝写）。"""
    base = baseline_numbers()
    rel = MATRIX.relative_to(ROOT).as_posix()
    text = MATRIX.read_text(encoding="utf-8")
    result_re = re.compile(r"^\| 结果 \|.*$", re.M)
    date_re = re.compile(r"^\| 日期 \|.*$", re.M)
    old_result = result_re.search(text)
    old_date = date_re.search(text)
    if not old_result or not old_date:
        print("FAIL: matrix §0.1 rows not found", file=sys.stderr)
        return 1
    new_result = (
        f"| 结果 | **{base['suites']} 套件 / {base['passed']} passed / {base['failed']} failed / "
        f"{base['ignored']} ignored**（单一真源 [test-baseline.md](test-baseline.md)） |"
    )
    new_date = f"| 日期 | {base['date']} |"
    print(f"§0.1 结果: {old_result.group(0).strip()}")
    print(f"     =>  {new_result}")
    print(f"§0.1 日期: {old_date.group(0).strip()}")
    print(f"     =>  {new_date}")
    old_nums = re.search(
        r"(\d+)\s*套件\s*/\s*(\d+)\s+passed\s*/\s*(\d+)\s+(?:failed|product-failed).*?(\d+)\s+ignored",
        old_result.group(0),
    )
    old_day = re.search(r"(\d{4}-\d{2}-\d{2})", old_date.group(0))
    if old_nums and old_day and (
        int(old_nums.group(1)),
        int(old_nums.group(2)),
        int(old_nums.group(3)),
        int(old_nums.group(4)),
        old_day.group(1),
    ) == (base["suites"], base["passed"], base["failed"], base["ignored"], base["date"]):
        print("OK: matrix §0.1 已与单一真源一致（含 product-failed 口径），无需更新")
        return 0
    dirty = _run(["git", "status", "--porcelain", "--", rel]).stdout.strip()
    if dirty:
        print(f"WARN: {rel} 有未提交改动（他线在途）；叠加不覆盖 → {'拒绝写入' if write and not force else '仅 dry-run'}")
        if write and not force:
            return 1
    if not write:
        print("dry-run: no file written；matrix 干净后加 --write。")
        return 0
    new_text = result_re.sub(lambda _: new_result, text, count=1)
    new_text = date_re.sub(lambda _: new_date, new_text, count=1)
    MATRIX.write_text(new_text, encoding="utf-8")
    print(f"updated: {rel}")
    return 0


def cmd_check() -> int:
    if not STATUS_DOC.exists():
        print(f"FAIL: {STATUS_DOC.relative_to(ROOT)} missing; run --gen", file=sys.stderr)
        return 1
    expected = render_status()
    actual = STATUS_DOC.read_text(encoding="utf-8")
    if expected != actual:
        print(f"FAIL: {STATUS_DOC.relative_to(ROOT)} drift; run --gen", file=sys.stderr)
        return 1
    # README 徽章必须与 test-baseline 单一真源一致（AGENTS §3 同日同口径）
    want = badge_url()
    bad = []
    for path in READMES:
        text = path.read_text(encoding="utf-8")
        match = BADGE_RE.search(text)
        if not match:
            bad.append(f"{path.relative_to(ROOT)}: tests badge not found")
        elif match.group(0) != want:
            bad.append(f"{path.relative_to(ROOT)}: badge {match.group(0)} != {want}")
    if bad:
        for item in bad:
            print(f"FAIL: {item}", file=sys.stderr)
        print("run: python scripts/docs_truth.py --gen-badges", file=sys.stderr)
        return 1
    print("OK: STATUS.md matches claims.yaml; README badges match baseline")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Docs Truth System (P0/P1)")
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--gen", action="store_true")
    parser.add_argument("--gen-badges", action="store_true", help="README tests 徽章 ← test-baseline 单一真源")
    parser.add_argument("--gen-matrix-01", action="store_true", help="matrix §0.1 结果/日期 ← 单一真源（默认 dry-run）")
    parser.add_argument("--write", action="store_true", help="配合 --gen-matrix-01 真正写盘")
    parser.add_argument("--force", action="store_true", help="忽略他线在途改动（不推荐）")
    parser.add_argument("--baseline-check", action="store_true", help="核对测试日志汇总 vs test-baseline §1")
    parser.add_argument("--log", default="", help="配合 --baseline-check 的 cargo test 日志路径")
    parser.add_argument("--matrix-check", action="store_true", help="matrix 环境变量/claims 开关一致性自查")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--block-stale", action="store_true", help="STALE 即 exit 1（P1c changed-claim 阻塞口径）")
    parser.add_argument("--strict", action="store_true", help="STALE / REVIEW_DUE / matrix 缺失也 exit 1")
    parser.add_argument("--claims", default=str(DEFAULT_CLAIMS))
    args = parser.parse_args(argv)
    claims_path = Path(args.claims)
    if not claims_path.is_absolute():
        claims_path = ROOT / claims_path
    if args.gen:
        return cmd_gen()
    if args.gen_badges:
        return sync_badges(write=True)
    if args.gen_matrix_01:
        return cmd_gen_matrix_01(args.write, args.force)
    if args.baseline_check:
        if not args.log:
            parser.error("--baseline-check requires --log <cargo test log>")
        return cmd_baseline_check(args.log)
    if args.matrix_check:
        return cmd_matrix_check(args.strict)
    if args.check:
        return cmd_check()
    if args.verify:
        return cmd_verify(claims_path, args.strict, args.block_stale)
    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
