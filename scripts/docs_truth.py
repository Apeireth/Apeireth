#!/usr/bin/env python3
"""文档事实体系（Docs Truth System）P0 工具。

唯一真源: docs/status/claims.yaml
生成物:   docs/status/STATUS.md（禁止手改）

用法:
  python scripts/docs_truth.py --verify                       # 核验（P0 report-only：结构错才 exit 1）
  python scripts/docs_truth.py --verify --strict              # STALE / REVIEW_DUE 也 exit 1
  python scripts/docs_truth.py --gen                          # 生成 STATUS.md
  python scripts/docs_truth.py --check                        # 生成物 drift 检查（drift = exit 1）
  python scripts/docs_truth.py --claims <path> ...            # 备用 claims 文件（测试用）

0 装口径: 没有证据的声明不写；核不到就 FAIL，不静默放行。
依赖: 仅标准库（PyYAML 可选；缺失时使用内置最小 YAML 子集解析器）。
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CLAIMS = ROOT / "docs" / "status" / "claims.yaml"
STATUS_DOC = ROOT / "docs" / "status" / "STATUS.md"
GENERATED_MARK = "<!-- GENERATED by scripts/docs_truth.py from docs/status/claims.yaml; do not edit -->"

LEVELS = (
    "IMPLEMENTED",
    "PRODUCTION WIRED",
    "DEFAULT ENABLED",
    "HARDWARE VALIDATED",
    "NOT IMPLEMENTED",
)
REQUIRED = ("id", "title", "level", "sources", "verified_at", "owner", "next_review")
LIST_KEYS = ("sources", "tests")


# ---------------------------------------------------------------- loading

def _scalar(text: str):
    text = text.strip()
    if not text:
        return None
    if len(text) >= 2 and text[0] == text[-1] and text[0] in ("'", '"'):
        return text[1:-1]
    low = text.lower()
    if low in ("null", "~"):
        return None
    if low == "true":
        return True
    if low == "false":
        return False
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    return text


def _load_minimal_yaml(text: str) -> dict:
    """解析本仓库 claims.yaml 用到的 YAML 子集（顶层标量 + claims 列表）。"""
    lines = []
    for raw in text.splitlines():
        stripped = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if stripped.strip():
            lines.append(stripped)

    data: dict = {}
    claims: list = []
    current: dict | None = None
    list_key: str | None = None
    in_claims = False
    for line in lines:
        indent = len(line) - len(line.lstrip(" "))
        body = line.strip()
        if body.startswith("#"):
            continue
        if not in_claims:
            if body == "claims:":
                in_claims = True
                data["claims"] = claims
                continue
            key, _, value = body.partition(":")
            data[key.strip()] = _scalar(value)
            continue
        if indent >= 4 and body.startswith("- ") and list_key:
            current.setdefault(list_key, []).append(_scalar(body[2:]))
            continue
        if indent <= 2 and body.startswith("- "):
            if current is not None:
                claims.append(current)
            current = {}
            list_key = None
            key, _, value = body[2:].partition(":")
            current[key.strip()] = _scalar(value)
            continue
        if current is None:
            continue
        key, _, value = body.partition(":")
        key = key.strip()
        if value.strip() == "":
            current[key] = []
            list_key = key
        else:
            current[key] = _scalar(value)
            list_key = None
    if current is not None:
        claims.append(current)
    return data


def load_claims(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    try:
        import yaml  # type: ignore
    except ImportError:
        return _load_minimal_yaml(text)
    data = yaml.safe_load(text) or {}
    data.setdefault("claims", [])
    return data


# ---------------------------------------------------------------- helpers

def _run(args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(args, cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace")


def grep_in_crates(needle: str) -> bool:
    proc = _run(["git", "grep", "-q", "--fixed-strings", needle, "--", "crates"])
    if proc.returncode in (0, 1):
        return proc.returncode == 0
    # fallback: 逐文件扫描（git 不可用时）
    for path in (ROOT / "crates").rglob("*"):
        if path.is_file() and path.suffix in (".rs", ".toml"):
            try:
                if needle in path.read_text(encoding="utf-8", errors="ignore"):
                    return True
            except OSError:
                continue
    return False


def changed_since(commit: str, sources: list[str]) -> list[str]:
    """返回 working tree（相对 commit）被改过的 sources。"""
    proc = _run(["git", "diff", "--name-only", commit, "--", *sources])
    if proc.returncode != 0:
        return [f"<git diff failed: {proc.stderr.strip()}>"]
    return [line.strip() for line in proc.stdout.splitlines() if line.strip()]


def _today() -> _dt.date:
    return _dt.date.today()


# ---------------------------------------------------------------- test baseline / README badge

BASELINE = ROOT / "docs" / "03-reference" / "test-baseline.md"
MATRIX = ROOT / "docs" / "03-reference" / "capabilities-matrix.md"
READMES = (ROOT / "README.md", ROOT / "README.zh-CN.md")
BADGE_RE = re.compile(r"tests-\d+%20passed%20%7C%20\d+%20failed%20\([0-9-]+\)-(?:success|critical)\.svg")


def baseline_numbers() -> dict:
    """从单一真源 test-baseline.md 读测试数字（不手抄）。"""
    text = BASELINE.read_text(encoding="utf-8")
    m = re.search(r"(\d+)\s*套件\s*/\s*(\d+)\s+passed\s*/\s*(\d+)\s+failed", text)
    if not m:
        raise SystemExit(f"cannot parse baseline numbers from {BASELINE}")
    d = re.search(r"\|\s*\*\*日期\*\*\s*\|\s*(\d{4}-\d{2}-\d{2})", text)
    if not d:
        raise SystemExit(f"cannot parse baseline date from {BASELINE}")
    return {
        "suites": int(m.group(1)),
        "passed": int(m.group(2)),
        "failed": int(m.group(3)),
        "date": d.group(1),
    }


def badge_url() -> str:
    n = baseline_numbers()
    dash_date = n["date"].replace("-", "--")
    status = "success" if n["failed"] == 0 else "critical"
    return f"tests-{n['passed']}%20passed%20%7C%20{n['failed']}%20failed%20({dash_date})-{status}.svg"


def sync_badges(write: bool) -> int:
    """把两份 README 的 tests 徽章同步为单一真源数字。"""
    want = badge_url()
    changed = 0
    for path in READMES:
        text = path.read_text(encoding="utf-8")
        new_text, count = BADGE_RE.subn(want, text)
        if count != 1:
            print(f"FAIL: expected exactly 1 tests badge in {path.relative_to(ROOT)}, found {count}", file=sys.stderr)
            return 1
        if new_text != text:
            changed += 1
            if write:
                path.write_text(new_text, encoding="utf-8")
            print(f"{'updated' if write else 'would update'}: {path.relative_to(ROOT)}")
    print(f"badge target: {want}  (baseline {baseline_numbers()})")
    if not changed:
        print("OK: badges already match baseline")
    return 0


def matrix_env_tokens() -> list[str]:
    text = MATRIX.read_text(encoding="utf-8")
    tokens: list[str] = []
    for m in re.finditer(r"APEIRETH_[A-Z0-9_]+", text):
        token = m.group(0)
        # 通配写法（APEIRETH_ENABLE_* / APEIRETH_DISABLE_*）跳过
        if text[m.end():m.end() + 1] == "*":
            continue
        if token.endswith("_"):
            continue
        tokens.append(token)
    return sorted(set(tokens))


def cmd_matrix_check(strict: bool) -> int:
    tokens = matrix_env_tokens()
    missing = [t for t in tokens if not grep_in_crates(t)]
    print(f"matrix env tokens: {len(tokens)}; missing in crates/: {len(missing)}")
    for token in missing:
        print(f"  MISSING: {token}")
    # claims 的 switch_env 应出现在 matrix（状态表与开关表互钉）
    data = load_claims(DEFAULT_CLAIMS)
    matrix_text = MATRIX.read_text(encoding="utf-8")
    claim_missing = [
        str(claim.get("switch_env"))
        for claim in data.get("claims") or []
        if claim.get("switch_env") and str(claim["switch_env"]) not in matrix_text
    ]
    if claim_missing:
        print(f"claims switch_env not present in matrix: {', '.join(claim_missing)}")
    if missing or claim_missing:
        return 1 if strict else 0
    print("OK: matrix env tokens all found in crates/; claims switches all present in matrix")
    return 0


# ---------------------------------------------------------------- commands

def cmd_verify(claims_path: Path, strict: bool) -> int:
    data = load_claims(claims_path)
    claims = data.get("claims") or []
    if not claims:
        print(f"FAIL: no claims in {claims_path}", file=sys.stderr)
        return 1

    seen: set[str] = set()
    rows: list[dict] = []
    errors = 0
    warnings = 0
    for i, claim in enumerate(claims, 1):
        cid = str(claim.get("id") or f"<claim-{i}>")
        problems: list[str] = []
        stale: list[str] = []

        if cid in seen:
            problems.append("duplicate id")
        seen.add(cid)
        for field in REQUIRED:
            if not claim.get(field):
                problems.append(f"missing field: {field}")
        level = claim.get("level")
        if level and level not in LEVELS:
            problems.append(f"unknown level: {level}")
        sources = claim.get("sources") or []
        if not isinstance(sources, list) or not sources:
            problems.append("sources must be a non-empty list")
            sources = []
        for src in sources:
            if not (ROOT / src).exists():
                problems.append(f"source missing: {src}")
        for test in claim.get("tests") or []:
            if not (ROOT / test).exists():
                problems.append(f"test path missing: {test}")
        switch = claim.get("switch_env")
        if switch and not grep_in_crates(str(switch)):
            problems.append(f"switch_env not found in crates/: {switch}")
        verified_at = claim.get("verified_at")
        if sources and verified_at:
            stale = changed_since(str(verified_at), sources)
        review_due = False
        next_review = claim.get("next_review")
        if next_review:
            try:
                review_due = _dt.date.fromisoformat(str(next_review)) < _today()
            except ValueError:
                problems.append(f"bad next_review date: {next_review}")

        if problems:
            status = "FAIL"
            errors += 1
        elif stale:
            status = "STALE"
            warnings += 1
        elif review_due:
            status = "REVIEW_DUE"
            warnings += 1
        else:
            status = "OK"
        rows.append(
            {
                "id": cid,
                "level": level,
                "default": claim.get("default"),
                "switch": switch,
                "status": status,
                "detail": "; ".join(problems + [f"changed: {s}" for s in stale[:3]]),
            }
        )

    width = max(len(r["id"]) for r in rows)
    print(f"{'id'.ljust(width)}  {'status':<10}  {'level':<18}  {'default':<7}  switch")
    print("-" * (width + 55))
    for r in rows:
        print(
            f"{r['id'].ljust(width)}  {r['status']:<10}  {str(r['level'] or '-'):<18}  "
            f"{str(r['default'] if r['default'] is not None else '-'):<7}  {r['switch'] or '-'}"
        )
        if r["detail"]:
            print(f"{''.ljust(width)}  -> {r['detail']}")
    print()
    print(f"claims={len(rows)} fail={errors} warn={warnings}")
    if errors:
        return 1
    if strict and warnings:
        return 1
    return 0


def render_status() -> str:
    data = load_claims(DEFAULT_CLAIMS)
    claims = data.get("claims") or []
    lines = [
        "# 文档状态仪表盘（STATUS）",
        "",
        GENERATED_MARK,
        f"> 真源：[claims.yaml](claims.yaml) · 生成器：`scripts/docs_truth.py --gen` · 更新：{data.get('updated_at', '-')}",
        "",
        "| id | level | default | switch_env | verified_at | next_review |",
        "|---|---|---|---|---|---|",
    ]
    for claim in claims:
        lines.append(
            "| `{id}` | {level} | {default} | {switch} | `{verified_at}` | {next_review} |".format(
                id=claim.get("id", "-"),
                level=claim.get("level", "-"),
                default=claim.get("default") if claim.get("default") is not None else "-",
                switch=f"`{claim['switch_env']}`" if claim.get("switch_env") else "-",
                verified_at=str(claim.get("verified_at", "-"))[:12],
                next_review=claim.get("next_review") or "-",
            )
        )
    lines += [
        "",
        "## 使用",
        "",
        "- 改状态：先改源码/测试 → 更新 `claims.yaml` 对应条的 `verified_at` → 跑 `python scripts/docs_truth.py --verify` → `--gen`。",
        "- `--verify` 的 STALE = 源码在 `verified_at` 之后被改过（该条声明需要复核）；FAIL = 证据缺失/开关不存在/字段不全。",
        "- P0 为 report-only（STALE 不阻塞 CI）；P1 起对 changed-claim 阻塞。",
        "",
    ]
    return "\n".join(lines)


def cmd_gen() -> int:
    STATUS_DOC.parent.mkdir(parents=True, exist_ok=True)
    STATUS_DOC.write_text(render_status(), encoding="utf-8")
    print(f"generated: {STATUS_DOC.relative_to(ROOT)}")
    return 0


def cmd_check() -> int:
    if not STATUS_DOC.exists():
        print(f"FAIL: {STATUS_DOC.relative_to(ROOT)} missing; run --gen", file=sys.stderr)
        return 1
    expected = render_status()
    actual = STATUS_DOC.read_text(encoding="utf-8")
    if expected != actual:
        print(f"FAIL: {STATUS_DOC.relative_to(ROOT)} drift; run --gen", file=sys.stderr)
        return 1
    # README 徽章必须与 test-baseline 单一真源一致（AGENTS §3 同日同口径）
    want = badge_url()
    bad = []
    for path in READMES:
        text = path.read_text(encoding="utf-8")
        match = BADGE_RE.search(text)
        if not match:
            bad.append(f"{path.relative_to(ROOT)}: tests badge not found")
        elif match.group(0) != want:
            bad.append(f"{path.relative_to(ROOT)}: badge {match.group(0)} != {want}")
    if bad:
        for item in bad:
            print(f"FAIL: {item}", file=sys.stderr)
        print("run: python scripts/docs_truth.py --gen-badges", file=sys.stderr)
        return 1
    print("OK: STATUS.md matches claims.yaml; README badges match baseline")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Docs Truth System (P0/P1)")
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--gen", action="store_true")
    parser.add_argument("--gen-badges", action="store_true", help="README tests 徽章 ← test-baseline 单一真源")
    parser.add_argument("--matrix-check", action="store_true", help="matrix 环境变量/claims 开关一致性自查")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--strict", action="store_true", help="STALE / REVIEW_DUE / matrix 缺失也 exit 1")
    parser.add_argument("--claims", default=str(DEFAULT_CLAIMS))
    args = parser.parse_args(argv)
    claims_path = Path(args.claims)
    if not claims_path.is_absolute():
        claims_path = ROOT / claims_path
    if args.gen:
        return cmd_gen()
    if args.gen_badges:
        return sync_badges(write=True)
    if args.matrix_check:
        return cmd_matrix_check(args.strict)
    if args.check:
        return cmd_check()
    if args.verify:
        return cmd_verify(claims_path, args.strict)
    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
