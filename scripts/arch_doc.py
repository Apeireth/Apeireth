#!/usr/bin/env python3
"""架构文档生成器（R0）：从契约 + cargo metadata 生成机器依赖图，并做防漂移检查。

唯一真源: docs/architecture/contract.toml（层/边规则/vendored）
生成物:   docs/architecture/ARCHITECTURE.generated.md（禁止手改）
数据:     cargo metadata --no-deps（只读，不构建）

用法:
  python scripts/arch_doc.py --gen      # 生成（评审后使用）
  python scripts/arch_doc.py --check    # 漂移检查（CI 用；drift = exit 1）
  python scripts/arch_doc.py --print    # 打印到 stdout

0 装口径: 只输出实测依赖边；生成物头部带 GENERATED 标记；check 不一致即红。
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover
    sys.exit("arch_doc: Python >= 3.11 required (tomllib)")

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "docs" / "architecture" / "contract.toml"
OUT = ROOT / "docs" / "architecture" / "ARCHITECTURE.generated.md"
MARK = "<!-- GENERATED by scripts/arch_doc.py from contract.toml + cargo metadata; do not edit -->"


def load_contract() -> dict:
    with open(CONTRACT, "rb") as fh:
        return tomllib.load(fh)


def metadata() -> tuple[dict[str, Path], dict[str, set[str]]]:
    proc = subprocess.run(
        ["cargo", "metadata", "--locked", "--no-deps", "--offline", "--format-version", "1"],
        cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8", errors="replace",
    )
    if proc.returncode != 0:
        raise SystemExit(f"arch_doc: cargo metadata failed:\n{proc.stderr[-2000:]}")
    data = json.loads(proc.stdout)
    names = {p["name"] for p in data["packages"]}
    roots: dict[str, Path] = {}
    prod: dict[str, set[str]] = {n: set() for n in names}
    for pkg in data["packages"]:
        name = pkg["name"]
        roots[name] = Path(pkg["manifest_path"]).parent
        for dep in pkg.get("dependencies", []):
            if dep.get("name") in names and dep.get("kind") != "dev":
                prod[name].add(dep["name"])
    return roots, prod


def layer_map(contract: dict) -> dict[str, str]:
    out: dict[str, str] = {}
    for layer, crates in contract.get("layers", {}).items():
        for crate in crates:
            out[crate] = layer
    return out


def render(contract: dict, prod: dict[str, set[str]]) -> str:
    layers = layer_map(contract)
    crates = sorted(prod)
    vendored = contract.get("vendored", {}).get("image_family", [])
    allowed = contract.get("deps", {}).get("allowed_layer_edges", [])
    flagged = {(e["from"], e["to"]) for e in contract.get("deps", {}).get("flagged_edges", [])}
    edges = sorted((s, d) for s in prod for d in prod[s])
    lines: list[str] = [
        MARK,
        "",
        "# ARCHITECTURE 依赖图（生成物）",
        "",
        "> 唯一真源：`docs/architecture/contract.toml`；数据：`cargo metadata --no-deps`（生产边，kind != dev）。",
        "> 重新生成：`python scripts/arch_doc.py --gen`；漂移检查：`python scripts/arch_doc.py --check`（CI）。",
        f"> 实测：workspace members = {len(prod)}，生产依赖边 = {len(edges)}。",
        "",
        "## 1. 层 → crate",
        "",
        "| 层 | crate |",
        "|---|---|",
    ]
    for layer in sorted(contract.get("layers", {})):
        names = sorted(contract["layers"][layer])
        note = "（vendored 家族，门禁隔离见 ADR-0005 R4a）" if layer == "image_family" else ""
        lines.append(f"| **{layer}**{note} | {', '.join(f'`{n}`' for n in names)} |")
    lines += [
        "",
        "## 2. 生产依赖边（实测）",
        "",
        "| from | to | 层方向 |",
        "|---|---|---|",
    ]
    for src, dst in edges:
        a, b = layers.get(src, "?"), layers.get(dst, "?")
        mark = "" if a == "?" or b == "?" else (" ✅" if _pair_allowed(a, b, allowed) else " ⚠️未登记")
        if (src, dst) in flagged:
            mark += " 🚩flagged"
        lines.append(f"| `{src}` | `{dst}` | {a} → {b}{mark} |")
    lines += [
        "",
        "## 3. 契约登记的 flagged 边（待裁决债务，不是许可）",
        "",
    ]
    if flagged:
        for src, dst in sorted(flagged):
            lines.append(f"- `{src}` → `{dst}`")
    else:
        lines.append("- （无）")
    comp = contract.get("composition_roots", [])
    if comp:
        lines += ["", "## 4. 装配根（登记）", ""]
        for entry in comp:
            lines.append(f"- `{entry['crate']}` / `{entry['file']}` — {entry['role']}")
    lines += ["", "## 5. 层方向允许表（契约）", ""]
    for rule in allowed:
        lines.append(f"- `{rule}`")
    lines.append("")
    return "\n".join(lines)


def _pair_allowed(a: str, b: str, rules: list[str]) -> bool:
    for rule in rules:
        if "->" not in rule:
            continue
        left, right = [x.strip() for x in rule.split("->", 1)]
        if left == a and (right == "*" or right == b):
            return True
    return False


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    parser = argparse.ArgumentParser(description="architecture doc generator")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--gen", action="store_true")
    group.add_argument("--check", action="store_true")
    group.add_argument("--print", dest="print_only", action="store_true")
    args = parser.parse_args(argv)

    contract = load_contract()
    _roots, prod = metadata()
    content = render(contract, prod)

    if args.print_only:
        print(content)
        return 0
    if args.gen:
        OUT.write_text(content, encoding="utf-8")
        print(f"[arch_doc] generated: {OUT.relative_to(ROOT)}")
        return 0
    if not OUT.exists():
        print(f"[arch_doc] FAIL: missing {OUT.relative_to(ROOT)} (run --gen)")
        return 1
    current = OUT.read_text(encoding="utf-8")
    if current != content:
        print(f"[arch_doc] FAIL: {OUT.relative_to(ROOT)} 已漂移（重新 --gen 并在提交正文说明）")
        return 1
    print(f"[arch_doc] OK: {OUT.relative_to(ROOT)} 与契约+metadata 一致")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
