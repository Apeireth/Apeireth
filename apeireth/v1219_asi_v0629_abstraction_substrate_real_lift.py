def main(argv: Optional[List[str]] = None) -> int:
    parser_args = argv if argv is not None else sys.argv[1:]
    mode = "default"
    md_out: Optional[str] = None
    artifact_out: Optional[str] = None
    i = 0
    while i < len(parser_args):
        a = parser_args[i]
        if a == "--measure":
            mode = "measure"
        elif a == "--json":
            mode = "json"
        elif a == "--report":
            mode = "report"
        elif a == "--md-out":
            i += 1
            md_out = parser_args[i] if i < len(parser_args) else None
        elif a == "--artifact":
            i += 1
            artifact_out = parser_args[i] if i < len(parser_args) else None
        elif a == "--full":
            mode = "full"
        i += 1

    rep = measure_v1219_full()

    if mode == "measure":
        print(f"V1219 AB dim realized: {rep.v1219_ab_dim_realized:.4f} ({rep.v1219_ab_dim_cell_count} cells)")
        print(f"V1219 ASI overall realized (112 cell): {rep.v1219_overall_realized_112:.4f}")
