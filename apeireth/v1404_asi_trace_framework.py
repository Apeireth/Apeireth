def coherence_check(capacities: List[TraceCapacity],
                    limits: List[TraceLimit]) -> List[TraceCoherenceCheck]:
    """12 真 pair-wise 一致性 checks"""
    checks: List[TraceCoherenceCheck] = []

    # 6 pair: top-6 caps vs LIM_NOT_ASI_REACHED
    for cap in capacities[:6]:
        # at least 1 evidence must contain V# ref or commit or tests
        passes = bool(cap.evidence) and any(
            "V" in e or "commit" in e.lower() or "tests" in e.lower() for e in cap.evidence
        )
        checks.append(TraceCoherenceCheck(
            pair=f"{cap.cap_id} ∩ LIM_NOT_ASI_REACHED",
            passes=passes,
            reason=f"{cap.cap_id} 有真 evidence (≥1 V# ref), 不假装 ASI 达成" if passes
                  else f"{cap.cap_id} 缺真 evidence, 需 fix",
        ))

    # 6 pair: top-6 caps vs LIM_NOT_PHENOMENAL_TRACE
    for cap in capacities[:6]:
        passes = all("≠" in l.description or "not" in l.name.lower()
                     for l in limits[:1])
        checks.append(TraceCoherenceCheck(
            pair=f"{cap.cap_id} ∩ LIM_NOT_PHENOMENAL_TRACE",
            passes=passes,
            reason=f"{cap.cap_id} declare LIM_NOT_PHENOMENAL_TRACE, 不假装 Phenomenal trace awareness"
                  if passes else f"{cap.cap_id} 缺 Phenomenal trace guard",
        ))

    return checks


