def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="v1404",
        description="V1404 ASI 真生产 迹 (Trace) framework CLI",
    )
    parser.add_argument("--format", choices=["text", "json", "md"], default="text",
                        help="output format (default: text)")
    parser.add_argument("--json", action="store_true",
                        help="JSON output for chain command")

    sub = parser.add_subparsers(dest="cmd")

    p_version = sub.add_parser("version", help="show V1404 version")
    p_version.set_defaults(handler=_cli_version)

    p_report = sub.add_parser("trace-report", help="full trace report")
    p_report.set_defaults(handler=_cli_trace_report)

    p_cap = sub.add_parser("capacity", help="list 12 trace capacities")
    p_cap.set_defaults(handler=_cli_capacity)

    p_lim = sub.add_parser("limits", help="list 6 trace limits")
    p_lim.set_defaults(handler=_cli_limits)

    p_lin = sub.add_parser("lineage", help="list lineage chain V1256 → V1404")
    p_lin.set_defaults(handler=_cli_lineage)

    p_time = sub.add_parser("timeline", help="list timeline of meta decisions")
    p_time.set_defaults(handler=_cli_timeline)

    p_branch = sub.add_parser("branch", help="list branch lineage")
    p_branch.set_defaults(handler=_cli_branch)

    p_cite = sub.add_parser("citation", help="list 7 prior figure citations")
    p_cite.set_defaults(handler=_cli_citation)

    p_chain = sub.add_parser("chain", help="chain delegate V1400 + V1401 + V1402 + V1403")
    p_chain.set_defaults(handler=_cli_chain)

    p_pop = sub.add_parser("popper", help="popper self-test (7 cases)")
    p_pop.set_defaults(handler=_cli_popper)

    p_demo = sub.add_parser("demo", help="V1404 demo")
    p_demo.set_defaults(handler=_cli_demo)

    p_help = sub.add_parser("help", help="show help")
    p_help.set_defaults(handler=_cli_help)

    return parser


def run_cli(argv: Optional[Sequence[str]] = None) -> int:
    parser = _build_parser()
    if argv is None:
        argv = sys.argv[1:]
    if not argv or argv == ["help"] or argv == ["--help"] or argv == ["-h"]:
        _cli_help()
        return 0
    try:
        args = parser.parse_args(argv)
    except SystemExit as e:
        return int(getattr(e, "code", 2) or 2)
    handler = getattr(args, "handler", None)
    if handler is None:
        _cli_help()
        return 2
    return int(handler(args) or 0)


if __name__ == "__main__":
    sys.exit(run_cli())