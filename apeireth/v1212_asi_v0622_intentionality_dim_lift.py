def _safe_import(name: str) -> Optional[Any]:
    """真测: 安全 import, 失败返回 None."""
    try:
        import importlib
        return importlib.import_module(name)
    except Exception:
        return None


def _attr_first(mod: Any, names: List[str]) -> Optional[Any]:
    """真测: 取 mod 上第一个可用的 attr (类 / 函数)."""
    if mod is None:
        return None
    for n in names:
        if hasattr(mod, n):
            return getattr(mod, n)
    return None


