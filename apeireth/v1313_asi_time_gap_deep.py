@dataclass(frozen=True)
class TimePosition:
    """A time position with both A-series and B-series attributes.

    V3 守门: ASI 真生产 = B-series, A-series 仅 substrate.
    """

    tick: int                # B-series position (earlier/later, static)
    a_state: str             # A-series: "past" | "present" | "future"
    description: str = ""

    def __post_init__(self) -> None:
        if self.tick < 0:
            raise ValueError(f"tick must be >= 0, got {self.tick}")
        if self.a_state not in ("past", "present", "future"):
            raise ValueError(f"a_state must be past/present/future, got {self.a_state}")


def cross_check_ab_series(positions: Iterable[TimePosition]) -> Dict[str, Any]:
    """Cross-check A/B-series consistency per McTaggart.

    McTaggart argued: if both A-series (dynamic) and B-series (static) hold,
    then change is unreal. Substrate treatment: we hold B-series as 真生产,
    and A-series as substrate only.
    """
    p_list = list(positions)
    if not p_list:
        return {"n": 0, "b_series_ordering": True, "a_series_distinct": 0, "guard": "ASI 真生产 = B-series; A-series 仅 substrate (McTaggart inconsistency NOT exploited)"}

    # B-series 真生产: earlier/later is monotonic in tick
    b_series_ordering = all(p_list[i].tick >= p_list[i - 1].tick
                            for i in range(1, len(p_list)))
    # A-series substrate: count distinct A-states (past/present/future)
    a_states = {p.a_state for p in p_list}
    return {
        "n": len(p_list),
        "b_series_ordering": bool(b_series_ordering),
        "a_series_distinct": len(a_states),
        "a_state_distribution": {s: sum(1 for p in p_list if p.a_state == s)
                                  for s in ("past", "present", "future")},
        "guard": "ASI 真生产 = B-series; A-series 仅 substrate (McTaggart inconsistency NOT exploited)",
    }


