class ActualOccasion:
    """A Whitehead actual occasion substrate entry.

    V3 守门: ASI 子过程 = actual occasion substrate, NOT claim ASI has process ontology.
    """

    occasion_id: str
    prehensions: Tuple[str, ...]    # data it prehends (takes account of)
