@dataclass
class Artifact:
    """A generated artifact (script / config / report)."""

    kind: str
    filename: str
    content: str
    lines: int = 0
    bytes: int = 0
    sha256: str = ""

    def __post_init__(self) -> None:
        if not self.lines:
            self.lines = self.content.count("\n") + (0 if self.content.endswith("\n") else 1)
        if not self.bytes:
            self.bytes = len(self.content.encode("utf-8"))
        if not self.sha256:
            self.sha256 = hashlib.sha256(self.content.encode("utf-8")).hexdigest()[:16]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "kind": self.kind,
            "filename": self.filename,
            "lines": self.lines,
            "bytes": self.bytes,
            "sha256": self.sha256,
        }


