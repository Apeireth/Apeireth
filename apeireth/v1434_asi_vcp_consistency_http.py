def _cmd_all(args: List[str]) -> int:
    """Write all artifacts to OUTPUT_DIR."""
    outdir = OUTPUT_DIR
    if args and not args[0].startswith("-"):
        outdir = Path(args[0])
    outdir.mkdir(parents=True, exist_ok=True)
    arts = build_all_artifacts()
    index_lines: List[str] = []
    index_lines.append(f"# V1434 Artifacts Index")
    index_lines.append(f"- outdir: `{outdir.resolve()}`")
    index_lines.append(f"- generated: `{_now_iso()}`")
    index_lines.append("")
    index_lines.append("| kind | filename | lines | bytes | sha256 |")
    index_lines.append("|---|---|---|---|---|")
    for a in arts:
        path = outdir / a.filename
        path.write_text(a.content, encoding="utf-8")
        index_lines.append(
            f"| {a.kind} | `{a.filename}` | {a.lines} | {a.bytes} | `{a.sha256}` |"
        )
    (outdir / "INDEX.md").write_text("\n".join(index_lines) + "\n", encoding="utf-8")
    print(f"wrote {len(arts)} artifacts to {outdir.resolve()}")
    for a in arts:
        print(f"  - {a.filename} ({a.lines} lines, {a.bytes} bytes)")
    return 0


_COMMANDS: Dict[str, Any] = {
    "version": _cmd_version,
    "meta": _cmd_meta,
    "help": _cmd_help,
    "popper": _cmd_popper,
    "chain": _cmd_chain,
    "python": _cmd_python,
    "nginx": _cmd_nginx,
    "compose": _cmd_compose,
    "json": _cmd_json,
    "summary": _cmd_summary,
    "all": _cmd_all,
}


def main(argv: Optional[List[str]] = None) -> int:
    """CLI entry point."""
    args = list(sys.argv[1:] if argv is None else argv)
    if not args:
        return _cmd_help(args)
    cmd = args[0]
    if cmd not in _COMMANDS:
        print(f"unknown command: {cmd}")
        print("available: " + ", ".join(_COMMANDS.keys()))
        return 1
    return _COMMANDS[cmd](args[1:])


if __name__ == "__main__":
    sys.exit(main())