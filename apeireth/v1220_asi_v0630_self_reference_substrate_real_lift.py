def main(argv: Optional[List[str]] = None) -> int:
    parser_args = argv if argv is not None else sys.argv[1:]
    mode = "default"
    md_out: Optional[str] = None
    artifact_out: Optional[str] = None
    i = 0
    while i < len(parser_args):
        a = parser_args[i]
        if a == "--measure":
            mode = "measure"
        elif a == "--json":
            mode = "json"
        elif a == "--report":
            mode = "report"
        elif a == "--md-out":
            i += 1
            md_out = parser_args[i] if i < len(parser_args) else None
        elif a == "--artifact":
            i += 1
            artifact_out = parser_args[i] if i < len(parser_args) else None
        elif a == "--full":
            mode = "full"
        i += 1

    rep = measure_v1220_full()

    if mode == "measure":
        print(f"V1220 SF dim realized: {rep.v1220_sf_dim_realized:.4f} ({rep.v1220_sf_dim_cell_count} cells)")
        print(f"V1220 ASI overall realized (118 cell): {rep.v1220_overall_realized_118:.4f}")
        print(f"V1220 ASI overall mean (169 cell): {rep.v1220_overall_mean_169:.4f}")
