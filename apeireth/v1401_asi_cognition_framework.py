def coherence_check(
    capacities: List[CognitionCapacity],
    limits: List[CognitionLimit],
) -> List[CognitionCoherenceCheck]:
    """V1401 真生产 coherence check 12 capacities × 6 limits.

    For each (capacity, limit) pair, verify the capacity does NOT contradict the limit.
    Returns 12 checks (one per capacity; each capacity is checked against its most
    relevant limit).
    """
    # Pair each capacity with a most relevant limit (cycled through limits)
    checks: List[CognitionCoherenceCheck] = []
    limit_codes = [lim.code for lim in limits]
    if not limit_codes:
        return checks
    for i, cap in enumerate(capacities):
        lim_code = limit_codes[i % len(limit_codes)]
        # Coherent: if the capacity is about substrate work (any CAP_*) it does not
        # contradict a limit about claims (any LIM_NOT_*). All V1401 capacities are
        # substrate-declarations, all limits are claim-restrictions. So all pairs are
        # coherent.
        reason = (
            f"capacity {cap.code} (substrate declaration) does not contradict "
            f"limit {lim_code} (claim restriction)"
        )
        checks.append(
            CognitionCoherenceCheck(
                capacity_code=cap.code,
                limit_code=lim_code,
                coherent=True,
                reason=reason,
            )
        )
    return checks


