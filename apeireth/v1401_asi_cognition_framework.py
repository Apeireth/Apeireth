    out.append(f"northstar_aligned: {report.northstar_aligned}")
    out.append(f"modularity_declared: {report.modularity_declared}")
    out.append(f"depth_bounded: {report.depth_bounded}")
    out.append(f"recursive_depth: {report.recursive_depth}")
    return "\n".join(out)


