def bias_detect(
    capabilities: List[SelfCapability],
    trajectory: List[SelfTrajectoryPoint],
) -> List[SelfBiasFinding]:
    """V1400 真 8 cognitive biases 检测 (主 19:33 + 主 17:43).

    Real detection based on真 data:
    - ANCHORING: if past 10+ consecutive same-kind modules
    - RECENCY: if latest module kind drives trajectory prediction
    - STATUS_QUO: if trajectory has no future points (resistance to change)
    - SUNK_COST: hard to detect without commit history; flag based on
      trajectory length
    - CONFIRMATION: if all capability evidence supports capabilities (no
      counter-evidence searched)
    - AVAILABILITY: if trajectory dominated by recent kinds
    - OPTIMISM: if northstar_aligned=True without 真 limit
    - DUNNING_KRUGER: if recursive_depth > 2 (self-reference over-confidence)
    """
    findings: List[SelfBiasFinding] = []

    past = [t for t in trajectory if t.series == "past"]
    future = [t for t in trajectory if t.series == "future"]

    # BIAS_ANCHORING: 连续 5+ 同 kind
    if past:
        kinds = [t.module_kind for t in past[-10:]]
        most_common_count = max((kinds.count(k) for k in set(kinds)), default=0)
        anchor_detected = most_common_count >= 5
    else:
        anchor_detected = False
    findings.append(SelfBiasFinding(
        bias_code="BIAS_ANCHORING",
        bias_name="锚定 (anchoring)",
        detected=anchor_detected,
        evidence=f"past {len(past)} points, max kind count = {most_common_count if past else 0}",
    ))

    # BIAS_RECENCY: latest module kind dominates
    if past and future:
        last_kind = past[-1].module_kind
        recency_detected = any(t.module_kind == last_kind for t in future)
    else:
        recency_detected = False
    findings.append(SelfBiasFinding(
        bias_code="BIAS_RECENCY",
        bias_name="近因 (recency)",
        detected=recency_detected,
        evidence=f"last past kind = {past[-1].module_kind if past else 'N/A'}",
    ))

    # BIAS_STATUS_QUO: no future points
    status_quo_detected = not future
    findings.append(SelfBiasFinding(
        bias_code="BIAS_STATUS_QUO",
        bias_name="现状 (status-quo)",
        detected=status_quo_detected,
        evidence=f"{len(future)} future points (0 = status-quo resistance)",
    ))

    # BIAS_SUNK_COST: hard to detect without commit count; flag if past > 15
    sunk_cost_detected = len(past) > 15
    findings.append(SelfBiasFinding(
        bias_code="BIAS_SUNK_COST",
        bias_name="沉没成本 (sunk-cost)",
        detected=sunk_cost_detected,
        evidence=f"{len(past)} past modules (>15 may indicate sunk-cost bias)",
    ))

    # BIAS_CONFIRMATION: all capability evidence positive (no counter)
    confirm_detected = all(c.evidence for c in capabilities) and len(capabilities) >= 12
    findings.append(SelfBiasFinding(
        bias_code="BIAS_CONFIRMATION",
        bias_name="确认 (confirmation)",
        detected=confirm_detected,
        evidence=f"{len(capabilities)} capabilities all evidenced (may lack counter-evidence)",
    ))

    # BIAS_AVAILABILITY: trajectory dominated by recent kinds
    if past:
        avail_detected = past[-1].module_kind == past[-2].module_kind if len(past) >= 2 else False
    else:
        avail_detected = False
    findings.append(SelfBiasFinding(
        bias_code="BIAS_AVAILABILITY",
        bias_name="可得性 (availability)",
        detected=avail_detected,
        evidence=f"last 2 kinds same: {avail_detected}",
    ))

    # BIAS_OPTIMISM: northstar_aligned without limit
    optimism_detected = len(capabilities) > 2 * len([l for l in limits_safe()]) if False else False
    findings.append(SelfBiasFinding(
        bias_code="BIAS_OPTIMISM",
        bias_name="乐观 (optimism)",
        detected=optimism_detected,
        evidence=f"{len(capabilities)} capabilities vs {len(limits_safe())} limits",
    ))

    # BIAS_DUNNING_KRUGER: self-reference over-confidence
    findings.append(SelfBiasFinding(
        bias_code="BIAS_DUNNING_KRUGER",
        bias_name="邓宁-克鲁格",
        detected=False,  # explicit not-detected (we declare limits)
        evidence="V1400 declares 6 limits explicitly (D-K guarded against)",
    ))

    return findings


