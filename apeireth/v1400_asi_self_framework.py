def run_cli(argv: Optional[Sequence[str]] = None) -> int:
    """V1400 真生产 CLI entrypoint.

    主 00:56 任何人都能接手: --help/-h 在 in-process 调用时 不触发 sys.exit,
    而是 print help 到 stdout 并返回 0 (与 subprocess 行为一致, 但不抛 SystemExit).
    """
    parser = _build_parser()
    # V1400 真生产 --help handling: 防止 argparse 的 SystemExit 影响 in-process 测试
    if argv is not None:
        if "--help" in argv or "-h" in argv:
            parser.print_help()
            return 0
    try:
        args = parser.parse_args(argv)
    except SystemExit:
        # argparse 异常路径 (理论上已被 --help 短路, 兜底)
        parser.print_help()
        return 0
    if args.command == "version":
        return _cli_version()
    if args.command == "self-report":
        return _cli_self_report(args)
    if args.command == "coherence":
        return _cli_coherence(args)
    if args.command == "trajectory":
        return _cli_trajectory(args)
    if args.command == "bias":
        return _cli_bias(args)
    if args.command == "northstar":
        return _cli_northstar(args)
    if args.command == "audit":
        return _cli_audit(args)
    if args.command == "popper":
        return _cli_popper()
    if args.command == "demo":
        return _cli_demo(args)
    if args.command == "chain":
        return _cli_chain(args)
    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(run_cli())
